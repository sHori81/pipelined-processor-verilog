module seg7decoder(
 input [3:0] a,
 input minus,
 input blank,
 output [7:0] out,
 output sel);

 assign out = blank ? 8'b00000000:
              minus ? 8'b00000010:
              (a==4'b0000) ? 8'b11111100:
         	(a==4'b0001) ? 8'b01100000:
   			  (a==4'b0010) ? 8'b11011010:
   			  (a==4'b0011) ? 8'b11110010:
   			  (a==4'b0100) ? 8'b01100110:
   			  (a==4'b0101) ? 8'b10110110:
   			  (a==4'b0110) ? 8'b10111110:
   			  (a==4'b0111) ? 8'b11100000:
   			  (a==4'b1000) ? 8'b11111110:
   			  (a==4'b1001) ? 8'b11110110:
   			  (a==4'b1010) ? 8'b11101110:
   			  (a==4'b1011) ? 8'b00111110:
   			  (a==4'b1100) ? 8'b00011010:
   			  (a==4'b1101) ? 8'b01111010:
   			  (a==4'b1110) ? 8'b10011110:
   			             	8'b10001110;
	assign sel = 0;
endmodule
